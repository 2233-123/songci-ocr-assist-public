package com.songci.assist

/**
 * 全局可调参数。真机调参后在这里固化，**不要**把阈值散落在业务代码里。
 */
object Config {

    // ------------------------------------------------------------------ 取帧
    /**
     * **默认**取帧档位（fps）。
     *
     * ### 为什么曾经从 2 提到 8
     *
     * 原值是 2 fps，依据是"OCR 约 300ms/帧"的估算。**但真机基准实测 ML Kit 中文模型
     * 单帧只要 ~113ms（最快 69ms，29 帧中位）** —— 那个 300ms 的估算偏高，而
     * 500ms 的时间闸实际上成了唯一的限速器：
     *
     * ```
     * OCR 113ms  → 本可 8.8 fps
     * 节流 500ms → 强制 2 fps（83% 的时间纯空转）
     * ```
     *
     * ### 现在它只是默认值
     *
     * 用户可在「性能」设置里改档位（见 [FPS_CHOICES]）—— 实测吞吐约 4~5 次/秒，
     * 不同玩家对"响应速度 vs 耗电发热"的偏好不同，所以不再写死。
     */
    const val DEFAULT_FPS = 8

    /**
     * 旧的固定间隔常量 —— **已废弃**，仅保留给历史测试引用。
     *
     * 运行时一律走 [intervalMsForFps] / [idleIntervalMsForFps]（按用户档位算）。
     */
    @Deprecated("改用 intervalMsForFps(fps)")
    val MIN_FRAME_INTERVAL_MS: Long = intervalMsForFps(DEFAULT_FPS)   // 125ms

    /** @see MIN_FRAME_INTERVAL_MS */
    @Deprecated("改用 idleIntervalMsForFps(fps)")
    val IDLE_FRAME_INTERVAL_MS: Long = idleIntervalMsForFps(DEFAULT_FPS)  // 500ms

    /** 未命中连续多少帧后进入省电模式 */
    const val FRAMES_BEFORE_IDLE = 30

    /** 取帧缩放到宽度不超过该值（高度按比例） */
    const val MAX_FRAME_WIDTH = 1080

    /** 命中后多久内不重复跑第二段 OCR（同一局结果不变） */
    const val HIT_COOLDOWN_MS = 3_000L

    /**
     * 连续多久无命中后清除高亮（例如已经选完）。
     *
     * **必须大于省电模式的帧间隔** [IDLE_INTERVAL_MAX_MS]，否则高亮会在两帧之间闪一下。
     */
    const val HIGHLIGHT_TTL_MS = 2_500L

    // ------------------------------------------------------------------ 遮挡守护
    /**
     * 游戏画「首句」的纵向位置（归一化，屏幕高度比例）。
     *
     * 历次真机日志实测：**60/60 次都在 0.19**。
     *
     * ### 为什么它是配置项而不是注释
     *
     * 状态条是 App **自己画在屏幕顶部**的浮层，而首句是**取帧时一起被 OCR 的**。
     * 状态条一旦盖住首句，OCR 就读不到它 —— 表现为「识别不出新句子」，
     * 而用户会以为是识别引擎不行。**App 遮住自己要读的字**，这个错误非常隐蔽。
     *
     * 真机事故（v0.11.0）：把效果做成状态条**第二行**后，该局 95 帧里
     * **90 帧「首句未匹配」**，同时顶部按钮也点不动了。
     *
     * 所以这里留一个可被 [OverlayService] 检查的常量，越界就打 `overlay.occlusion`
     * 警告 —— 让这个错误**可观测**，而不是等用户反馈。
     */
    const val GAME_HEAD_LINE_RATIO = 0.19f

    /**
     * 状态条底边与首句之间要求的最小净空（归一化）。
     *
     * 低于此值视为**已构成遮挡风险**。[OverlayService] 会打警告日志。
     */
    const val MIN_HEAD_CLEARANCE_RATIO = 0.01f

    /**
     * 每个词牌最多记几条「气泡没找到」诊断（见 `FramePipeline.logOptionMiss`）。
     *
     * 取 3 而不是更多：这几条已经足够看清"OCR 把气泡读成了什么"，
     * 而事件环形缓冲只有 400 条 —— 记太多会把别的有用事件冲掉。
     */
    const val MAX_MISS_LOGS_PER_PAI = 3

    /**
     * **判定"这个 OCR 文本块属于 App 自绘区域"的重叠面积占比阈值**。
     *
     * 块与某个自绘矩形（状态条 / 调试面板 / 悬浮球）的交叠面积 ≥ 块自身面积的
     * 这个比例时，就把该块从匹配池里剔除。
     *
     * ### 为什么用"面积占比"而不是"中心点落入"
     *
     * 原实现只看块的**中心点**是否落在自绘矩形内。但 OCR 经常把状态条文字与相邻
     * 内容**并成一个大块**，此时块中心已经跑到矩形之外 → 整块都不被排除 →
     * 状态条里的词牌名被当成游戏气泡选中 → 框画到自己的文案上 →
     * 文字被读回又继续命中 → **框永不消失**（v0.10.x 那个自锁事故）。
     *
     * ### 为什么取 0.5
     *
     * - 太低（如 0.1）：只是**挨着**状态条的正常游戏文字会被误伤 → 漏识别
     * - 太高（如 0.9）：合并块（一大半在状态条上、一小半在游戏里）排不掉 → 又漏
     *
     * 0.5 = "这个块有一半以上压在自绘区域里"，既能抓住合并块，又不会波及邻居。
     */
    const val SELF_DRAWN_OVERLAP_RATIO = 0.5f

    // ------------------------------------------------------------------ 性能档位
    /**
     * 取帧频率的可选档位（用户可在设置里选）。
     *
     * ### 为什么需要它（用户需求）
     *
     * 原实现把 [FPS_NORMAL] 写死在代码里（8 fps）。实测吞吐只有 4~5 次/秒，
     * 但不同玩家/机型对"响应速度 vs 耗电发热"的偏好不同，所以交给用户选。
     *
     * ### 「不限速」档的真实含义
     *
     * `fps = 0` 表示**不加时间闸**，只留"上一帧没处理完就丢"这道闸
     * （见 `CaptureService.ocrBusy`）。它**不会**真的飙到 60 fps ——
     * OCR 本身 100~300ms 就是物理上限，实测约 3~10 次/秒。
     * 所以这一档实际是"让用户确认瓶颈不在时间闸"的对照档。
     *
     * ### 各档的间隔
     *
     * ```
     * 1 fps  → 1000ms      8 fps  →  125ms
     * 2 fps  →  500ms     15 fps  →   66ms
     * 4 fps  →  250ms      不限速 →    0ms
     * ```
     */
    val FPS_CHOICES: List<Int> = listOf(1, 2, 4, 8, 15, 0)

    /** 档位显示名（0 = 不限速） */
    fun fpsLabel(fps: Int): String = if (fps <= 0) "不限速" else "$fps fps"

    /** 档位 → 帧间隔（毫秒）。**[param fps] ≤ 0 表示不限速，返回 0。** */
    fun intervalMsForFps(fps: Int): Long =
        if (fps <= 0) 0L else (1000.0 / fps).toLong().coerceAtLeast(1L)

    /**
     * 省电间隔：在**用户选定档位**的基础上放慢，而不是写死 2000ms。
     *
     * ### 为什么不能继续写死 2000ms
     *
     * 用户选了 1 fps 时正常间隔就是 1000ms，而写死的省电间隔 2000ms 会让
     * "省电"变成"更慢"—— 反直觉。所以改成按倍数放慢：
     *
     * ```
     * 倍率 = 4，并夹在 [最小, 最大] 之间
     * 8 fps (125ms) → 500ms
     * 1 fps (1000ms) → 2000ms（夹到上限）
     * ```
     *
     * **上限必须小于 [HIGHLIGHT_TTL_MS]**，否则高亮会在两帧之间闪掉
     * （这是原来写死 2000ms 时踩过的约束，见 [HIGHLIGHT_TTL_MS] 注释）。
     */
    fun idleIntervalMsForFps(fps: Int): Long {
        val normal = intervalMsForFps(fps)
        if (normal <= 0L) return IDLE_INTERVAL_MAX_MS   // 不限速档：省电时直接取上限
        return (normal * IDLE_INTERVAL_FACTOR)
            .coerceIn(IDLE_INTERVAL_MIN_MS, IDLE_INTERVAL_MAX_MS)
    }

    /** 省电模式相对正常模式的放慢倍率 */
    const val IDLE_INTERVAL_FACTOR = 4L

    /**
     * 省电间隔下限。
     *
     * 不能太小，否则"省电"没有意义；8 fps 的 4 倍正好是 500ms，取它作下限。
     */
    const val IDLE_INTERVAL_MIN_MS = 500L

    /**
     * 省电间隔上限 = **1000ms**。
     *
     * 刻意远小于 [HIGHLIGHT_TTL_MS]（2500ms）：省电时帧与帧之间隔 1 秒，
     * 高亮仍能在下一帧到来前保持可见，不会"一闪一闪"。
     */
    const val IDLE_INTERVAL_MAX_MS = 1_000L

    /**
     * 命中正确选项后，把取帧放慢到该间隔（用户需求：等玩家点完再继续）。
     *
     * 不是完全停止：完全停帧有两个风险（自动切题时永不恢复、点击事件漏掉时卡死），
     * 所以用"放慢 + 玩家一点就立刻恢复 + 兜底超时"三件套，
     * 详见 [SLOWDOWN_AFTER_HIT_TIMEOUT_MS]。
     */
    const val SLOWDOWN_AFTER_HIT_INTERVAL_MS = 1_000L

    /**
     * 命中后降速状态的最长维持时间；超过则自动恢复用户设定档位（兜底）。
     *
     * 为什么要兜底：如果游戏**自动**切到下一题（不需要玩家点击），
     * 或注入的点击事件没被我们收到，降速状态就会一直挂着。
     * 有这个上限，最坏情况也只是几帧之内恢复正常节奏。
     */
    const val SLOWDOWN_AFTER_HIT_TIMEOUT_MS = 3_000L

    /**
     * 悬浮层窗口自身的 alpha 上限 —— 用来**规避 Android 12+ 的「不可信触摸遮挡」拦截**。
     *
     * ### 事故（真机日志，MuMu 模拟器 Android 12 / API 32 实测）
     *
     * 开了辅助后**整个游戏界面都点不动**。系统日志给出完整栈：
     *
     * ```
     * W InputDispatcher: Untrusted touch due to occlusion by com.songci.assist/10037
     *                    (obscuring opacity = 1.00, maximum allowed = 0.80)
     * D InputDispatcher: Stack of obscuring windows during untrusted touch (960, 540):
     *     * type=2038, package=com.songci.assist/10037, mode=USE_OPACITY, alpha=1.00,
     *       frame=[0,0][1920,1080], touchableRegion=[0,0][1920,1080],
     *       flags={... NOT_TOUCHABLE NOT_TOUCH_MODAL ...}
     *     * [TOUCHED] package=com.syyx.whrhx/10021, mode=BLOCK_UNTRUSTED
     * ```
     *
     * 关掉 `block_untrusted_touches` 后立刻恢复正常（A/B 已验证）。
     *
     * ### 机制：判定用 `Window.alpha`，**和窗口里画了什么无关**
     *
     * 日志里的 `mode=USE_OPACITY, alpha=1.00` 直接说明系统读的是**窗口 alpha**。
     * `WindowManager.LayoutParams.alpha` 默认 **1.0**，所以我们"视觉上几乎全透明"
     * 完全不起作用 —— 整屏 `FLAG_NOT_TOUCHABLE` 层的每次触摸都被丢弃，
     * 而且只写系统 logcat（`InputManager: Suppressing untrusted touch toast`），
     * **屏幕上什么提示都没有**，用户只会觉得"游戏点不动了"。
     *
     * Android 官方例外之一是「足够半透明的系统警报窗口」：组合不透明度 ≤ 0.80。
     *
     * ### 为什么取 0.70 而不是 0.80
     *
     * 0.80 是**临界值**（判定是 `> 0.80` 才拒），留 0.10 余量避免浮点/叠加误差。
     *
     * ### 代价
     *
     * **整个窗口的绘制内容都会变成 70% 不透明**，所以高亮框和状态条会比以前略淡。
     * 这是为了让触摸能透过去必须付的代价 —— 不能只改"看起来透明"的部分。
     *
     * ### 这是 v0.11.1 引入的回归
     *
     * ```
     * 0.6.0  全屏窗        → 华为上「按钮点不动」→ 0.6.1 改成按内容贴合的小窗
     * 0.11.0 小窗          → 「框从左上角飞过来」
     * 0.11.1 改回恒定整屏  → 动画修好了，但把 0.6.1 的遮挡问题带了回来
     * ```
     *
     * 用户手机上拦截开关恰好是关的（`block_untrusted_touches` 非默认值），
     * 所以一直没暴露；MuMu 是干净的默认配置，立刻暴露。
     */
    const val OVERLAY_WINDOW_ALPHA = 0.70f

    // ------------------------------------------------------------------ 裁剪区
    /**
     * OCR 前裁剪到 y ∈ [0, 这个比例]。
     *
     * 要看的两个区都在中上部：首句（y≈0.18）+ 词牌气泡（y≈0.30~0.60）。
     * 裁掉下方无用的立绘/按钮后**按原生分辨率识别**（不再把整帧缩到 41%，
     * 那样游戏的艺术字体会读不出来）。0.85 留足气泡下沿的余量。
     */
    const val OCR_CROP_BOTTOM = 0.85f

    /** 第一段：顶部区域，找词句首句。比例相对当帧高度 */
    const val TOP_CROP_TOP = 0.0f
    const val TOP_CROP_BOTTOM = 0.45f

    /** 第二段：中部区域，找词牌选项气泡 */
    const val MID_CROP_TOP = 0.30f
    const val MID_CROP_BOTTOM = 0.80f

    /**
     * 第二段挑候选块时，块中心 y 必须落在裁剪区内的这个子区间（防止把顶部状态条、
     * 底部按钮上的同名词牌也算成选项气泡）。
     */
    const val OPTION_REGION_TOP = 0.30f
    const val OPTION_REGION_BOTTOM = 0.80f

    // ------------------------------------------------------------- 补救识别横带
    /**
     * 补救识别读取的**窄横带**上沿（含首句行与三个气泡）。
     *
     * ### 为什么从 0.30~0.80 收窄到这里（真机实测）
     *
     * 日志 0107-014915 把「气泡被读到的 y 值」统计出来：
     *
     * ```
     * y=0.43  51 次      y=0.44  34 次     ← 中/右气泡，读得稳
     * y=0.31   2 次      y=0.57   2 次     ← 左气泡，几乎读不到
     * ```
     *
     * 而 `0.30~0.80` 这条 600px 高的带子里**绝大部分是噪声**：调试面板文字
     * （y 0.34~0.61，实测出现 151+148 次）、左侧立绘、右侧「豪放词情」标签。
     * 噪声越多，18px 手书小字越容易被整块挤掉。
     *
     * 收窄到 0.28~0.50（264px，约为原来的 1/2.4）后：
     * - 覆盖首句行（y≈0.19 下沿）到中/右气泡（0.43/0.44）与左气泡（≈0.36）
     * - 排除面板中心区（0.50~0.62）与下方立绘
     * - OCR 面积小 2.4 倍 → 更快，符合"以量取胜"
     */
    const val RETRY_BAND_TOP = 0.28f

    /** 补救识别的窄横带下沿，见 [RETRY_BAND_TOP] */
    const val RETRY_BAND_BOTTOM = 0.50f

    // ------------------------------------------------------------------ 匹配
    /**
     * 首句（词句）匹配的相似度阈值。
     *
     * ### 为什么是 0.65（经历了 0.72 → 0.70 → 0.65）
     *
     * 真机事故：`壮岁旌旗拥万夫锦襜突骑渡江初` 被 OCR 读成
     * **`当族旗拥万夫锦檐突骑`**（开头 `壮` 被吞、`岁`→`当`、`旌`→`族`），
     * 最优等长窗口相似度 **0.700**，0.72 时被拒。
     *
     * ### 各档实测（JVM 侧，同式算法；误报 = 画错词牌）
     *
     * | 场景 | 0.60 | **0.65** | 0.70 | 0.72 |
     * |---|---|---|---|---|
     * | 短首句错 1 字 | 100% | 100% | 100% | — |
     * | 短首句错 2 字 | 100% | **50%** | 25% | — |
     * | 短首句错 3 字 | 25% | **0.58%** | 0.58% | — |
     * | 全部 99 条错 2 字 | 100% | **97.98%** | 96.97% | — |
     * | **误报率** | **0.08%** ⚠️ | **0%** | 0% | 0% |
     *
     * **0.60 不可取**：5 字首句错 2 个 = `1 - 2/5 = 0.600`，恰好压线放行，
     * 于是出现 0.08% 的误报 —— 这是放宽阈值以来唯一一次"画错词牌"。
     *
     * **0.65 是那个干净的拐点**：卡在
     *
     * ```
     * 6 字首句错 2 个 = 0.667  → 放行 ✓
     * 5 字首句错 2 个 = 0.600  → 拒   （差 0.05）
     * ```
     *
     * 之间，拿到大部分收益而误报为 0。
     *
     * ### 为什么放宽是安全的
     *
     * 索引里 99 条首句，**任意两条（跨词牌）的最高编辑距离相似度只有 0.214**。
     * 阈值 0.65 距它有 **0.436** 的余量，所以这个阈值**不承担防误报的职责** ——
     * 唯一作用是在「提示率」与「不提示」之间取舍。
     *
     * ### 注意：调阈值并不能救所有题
     *
     * `壮岁旌旗` 那一题调阈值**没有用** —— 它的最优对齐在子串路径的 start=2，
     * 而子串候选只对齐开头（`alignAtZeroOnly = true`，当年为性能砍的）。
     * 补这条缺口需要一个兜底分支，已按用户要求**不做**：宁可那一题不提示。
     */
    const val SIMILARITY_THRESHOLD = 0.65

    /**
     * 气泡（词牌名）模糊匹配阈值。
     *
     * 词牌名全部是 3 字或 4 字，且**长度相同、相似度 ≥ 0.6 的词牌对一个都没有**
     * （已用索引校验）。所以：
     * - 阈值的意义是"同长度下最多错 1 个字" → 3 字对应 0.667、4 字对应 0.75；
     * - 取 0.66 让 3 字错 1 字也能救回来（例如「钗头凤」被 OCR 读错一个字）；
     * - 因为不存在同长度近似的词牌对，这个宽松度不会把 A 认成 B。
     */
    const val OPTION_SIMILARITY_THRESHOLD = 0.66

    /**
     * 气泡模糊匹配的「唯一最优」裕度：第一名必须比第二名高这么多才算数，
     * 否则宁可不出框（宁可不提示，也不误报）。
     */
    const val OPTION_SIMILARITY_MARGIN = 0.15

    /** 首句最短长度（索引校验同口径），过短不参与匹配 */
    const val MIN_HEAD_LEN = 5

    /** 首句在 Y 轴相邻多少像素内视为同一行，可拼接（两行折行的情况） */
    const val LINE_MERGE_TOLERANCE_RATIO = 0.6f

    /** 单帧最多拼接的行数，防止把整屏拼成一句 */
    const val MAX_MERGED_LINES = 2

    /**
     * 「同一行」允许的 X 轴交集上限（相对较窄块的宽度）。
     *
     * 真正被 OCR 拆成左右两段的话几乎不相交；交集过大说明是**两个各自独立**的块
     * （小块落在大块里、或同排的 UI 标签），拼起来只会把整句认错。
     */
    const val LINE_X_OVERLAP_MAX = 0.2f

    /**
